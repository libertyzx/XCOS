//=== 数据类型 ===========================================|

/**二值信号量句柄
 *  只负责一个任务;
 *
 */
typedef struct _XCSem_t{
    XCListBasic_t ListNode;     //链表节点
    XCTCB_t* phTCB;             //指向的TCB

    uint8_t Lock;               //锁
    uint8_t SemNum;             //信号值
}XCSemBin_t;

