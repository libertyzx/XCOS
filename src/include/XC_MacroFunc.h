//=== 二进制位操作 ========================================|

/************************************************|
 * 描述:    二进制0输出(低_Len位为0,剩余位为1)
 * 宏名:    _Bin0Out
 * 参数[I]: _Len    //总共几位0(对应低位,1-32)
 * 返回:    输出数据(最高32位数据),见例程
 * 说明:    见例程
 * 例程:
 *  uint8_t  Cache =  (uchar)_Bin0Out(3);   //8位数据, 输出:_B1111 11000
 *  uint16_t Cache = (ushort)_Bin0Out(3);   //16位数据,输出:_B1111 1111 1111 1000
 *  uint32_t Cache =  (ulong)_Bin0Out(3);   //32位数据,输出:_B1111 1111 1111 1111 1111 1111 1111 1000
 ************************************************/
#define _Bin0Out(_Len)      ( ((uint32_t)(~0) >> (_Len)) << (_Len) )

/************************************************|
 * 描述:    二进制1输出(低_Len位为1,剩余位为0)
 * 宏名:    _Bin1Out
 * 参数[I]: _Len    //总共几位1(对应低位,1-32)
 * 输出:    输出数据(最高32位数据),见例程
 * 说明:    见例程
 * 例程:
 *  uint8_t  Cache =  (uchar)_Bin1Out(1);   //8位数据, 输出:_B1
 *  uint16_t Cache = (ushort)_Bin1Out(3);   //16位数据,输出:_B111
 *  uint32_t Cache =  (ulong)_Bin1Out(9);   //32位数据,输出:_B0001 1111 1111
 ************************************************/
#define _Bin1Out(_Len)      (~(_Bin0Out(_Len)))

