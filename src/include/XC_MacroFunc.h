//=== 对应数据清除&置位 ===================================|

/************************************************|
 * 描述:    清除n位数据
 * 宏名:    _BitClr
 * 参数[I]: _Dest       //需要清除位的数据(最大32位类型)
 * 参数[I]: _Offset     //清除位的偏移(低位开始,0-31)
 * 参数[I]: _BitLen     //清零的位数(1-32)
 * 输出:    无
 * 说明:    见例程
 * 例程:
 *  uint32_t Cache = 0xFFFF;
 *  _BitClr(Cache, 3, 3);       //得到Cache为:0xFFC7
 ************************************************/
#define _BitClr(_Dest, _Offset, _BitLen)    do{ (_Dest) &= ~(_Bin1Out(_BitLen)<<(_Offset)); }while(0)

/************************************************|
 * 描述:    设置n位数据
 * 宏名:    _BitSet
 * 参数[I]: _Dest       //需要设置位的数据(最大32位类型)
 * 参数[I]: _Offset     //设置位的偏移(低位开始,0-31)
 * 参数[I]: _BitLen     //设置的位数(1-32)
 * 输出:    无
 * 说明:    见例程
 * 例程:
 *  uint32_t Cache = 0xF000;
 *  _BitSet(Cache, 3, 3);       //得到Cache为:0xF038
 ************************************************/
#define _BitSet(_Dest, _Offset, _BitLen)    do{ (_Dest) |= (_Bin1Out(_BitLen)<<(_Offset)); }while(0)

/************************************************|
 * 描述:    写n位数据
 * 宏名:    _BitWrite
 * 参数[I]: _Dest       //需要写入目标数据(最大32位类型)
 * 参数[I]: _Offset     //写入数据的偏移(低位开始,0-31)
 * 参数[I]: _Src        //写入的数据
 * 输出:    无
 * 说明:    不会清除原来的数据,只是与上;
 * 例程:
 *  uint32_t Cache = 0xF810;
 *  _BitWrite(Cache, 3, 3);     //得到Cache为:0xF818
 ************************************************/
#define _BitWrite(_Dest, _Offset, _Src)     do{ (_Dest) |= ((_Src)<<(_Offset)); }while(0)

/************************************************|
 * 描述:    读n位数据
 * 宏名:    _BitRead
 * 参数[I]: _Dest       //需要读取的目标数据(最大32位类型)
 * 参数[I]: _Offset     //读取数据的偏移(低位开始,0-31)
 * 参数[I]: _BitLen     //读取的位数(1-32)
 * 输出:    无
 * 说明:    读取的数据会位移到最低位;
 * 例程:
 *  uint32_t Cache = 0xFF5F;
 *  Cache = _BitRead(Cache, 3, 4);  //得到Cache为:0xB
 ************************************************/
#define _BitRead(_Dest, _Offset, _BitLen)   ( ( (_Dest)>>(_Offset) ) & _Bin1Out(_BitLen) )

/************************************************|
 * 描述:    更新n位数据(清除并写数据)
 * 宏名:    _BitUpdate
 * 参数[I]: _Dest       //需要写入目标数据(最大32位类型)
 * 参数[I]: _Offset     //写入数据的偏移(低位开始,0-31)
 * 参数[I]: _BitLen     //设置的位数(1-32)
 * 参数[I]: _Src        //写入的数据
 * 输出:    无
 * 说明:    会清除对应的位数,并将写入的数据和"_BitLen"与来确认输入数据准确性;
 * 例程:
 *  uint32_t Cache = 0xFFFF;
 *  _BitUpdate(Cache, 3, 9, 0xA);       //得到a为:0xF057
 ************************************************/
#define _BitUpdate(_Dest, _Offset, _BitLen, _Src)   \
    do{ \
        _BitClr(_Dest, _Offset, _BitLen);   \
        _BitWrite(_Dest, _Offset, ((_Src) & _Bin1Out(_BitLen)) );   \
    }while(0)

