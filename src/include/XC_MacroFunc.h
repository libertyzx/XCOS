/************************************************|
 * 描述:    由结构体成员获取结构体指针
 * 宏名:    _GetStructAddr
 * 参数[I]: _StructType     //结构体的类型
 * 参数[I]: _MemberName     //结构体成员名(只是名字)
 * 参数[I]: _MemberAddr     //结构体成员地址(指针)
 * 输出:    对应结构体类型的指针;
 * 说明:    注意,只能从1级成员得到结构体的指针;
 * 例程:
 *  typedef struct {
 *      uint32_t aa;
 *      uint32_t bb;
 *  }Test_t;
 *  Test_t Cache;
 *  Test_t *p;
 *  p = _GetStructAddr(Test_t, bb, &Cache->bb);
 *  //"p"的值等于"&Cache"的值;
 ************************************************/
#define _GetStructAddr(_StructType, _MemberName, _MemberAddr)   ( (_StructType*) (((uint8_t*)(_MemberAddr)) - offsetof(_StructType, _MemberName)) )

