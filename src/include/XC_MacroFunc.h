/************************************************|
 * 描述:    频率转换
 * 宏名:    _*Hz2Hz
 * 参数[I]: _n      //对应的频率
 * 输出:    无
 * 说明:    对应频率转Hz,支持*=K,M,G;
 * 例程:    无
 ************************************************/
#define _KHz2Hz(_n)     ((_n)*1000)                 /*KHz转Hz*/
#define _MHz2Hz(_n)     (_KHz2Hz(_n)*1000)          /*MHz转Hz*/
#define _GHz2Hz(_n)     (_MHz2Hz(_n)*1000)          /*GHz转Hz*/

/************************************************|
 * 描述:    获取数组元素个数
 * 宏名:    _ArraySize
 * 参数[I]: _a      //数组名;
 * 输出:    数组元素个数
 * 说明:    无
 *  sizeof(数组名);可以得到整个数组的占字节数;
 *  sizeof(数组名[0]);可以得到数组中单个元素大小;
 *  sizeof(数组名) / sizeof(数组名[0]) 即可得到数组元素大小;
 *  注意,只可用在数组,或数组指针上,若是纯指针或者形参是指针则不支持;
 * 例程:    无
 ************************************************/
#define _ArraySize(_a)  ( sizeof((_a)) / sizeof((_a)[0]) )

/************************************************|
 * 描述:    获取两个数中最大值
 * 宏名:    _Min
 * 参数[I]: _D1      //数值1
 * 参数[I]: _D2      //数值2
 * 输出:    _D1和_D2中大的值;
 * 说明:    无
 * 例程:    无
 ************************************************/
#define _Max(_D1, _D2)  (((_D1)>(_D2)) ? (_D1) : (_D2))

/************************************************|
 * 描述:    获取两个数中最小值
 * 宏名:    _Min
 * 参数[I]: _D1      //数值1
 * 参数[I]: _D2      //数值2
 * 输出:    _D1和_D2中小的值;
 * 说明:    无
 * 例程:    无
 ************************************************/
#define _Min(_D1, _D2)  (((_D1)<(_D2)) ? (_D1) : (_D2))

/************************************************|
 * 描述:    判断一个数是不是2的n次方
 * 宏名:    _TwoN
 * 参数[I]: _V      //数值
 * 输出:    boot    //1表示是2的n次方;0则不是;
 * 说明:    无
 * 例程:    无
 ************************************************/
#define _TwoN(_V)        ( ((_V)!=0) && ( ( (_V) & ((_V)-1) ) == 0) )

/************************************************|
 * 描述:    获取绝对值
 * 宏名:    _ABS
 * 参数[I]: _V      //数值
 * 输出:    输出绝对值
 * 说明:    无
 * 例程:    无
 ************************************************/
#define _ABS(_V)         ((_V)<0?(-(_V)):(_V))

/************************************************|
 * 描述:    设置不使用的变量
 * 宏名:    _Unused
 * 参数[I]: x       //变量名
 * 输出:    无
 * 说明:    不使用的变量用这个宏处理,防止编译器报警;
 * 例程:    无
 ************************************************/
#define _Unused(x)  ((void)(x))

/************************************************|
 * 描述:    从地址获取数据
 * 宏名:    _GetDataFromAddr*
 * 参数[I]: _Addr   //地址(整形变量/常量)
 * 输出:    获取地址中存储的数据
 * 说明:    从地址获取数据(*==8,16,32)
 * 例程:    无
 ************************************************/
#define _GetDataFromAddr8(_Addr)        ( *((__RW uint8_t*)(_Addr)) )       //输出8位数据
#define _GetDataFromAddr16(_Addr)       ( *((__RW uint16_t*)(_Addr)) )      //输出16位数据
#define _GetDataFromAddr32(_Addr)       ( *((__RW uint32_t*)(_Addr)) )      //输出32位数据

/************************************************ 我是分割线 ************************************************/

/************************************************|
 * 描述:    16进制数据转字符
 * 宏名:    _Hex2Char
 * 参数[I]: _Hex        //输入数据0x0-0xF(0-15)
 * 输出:    char        //字符('0'-'9','A'-'F')
 * 说明:    若是数据大于15,则只转换低4位,只输出大写字符;
 * 例程:    无
 ************************************************/
#define _Hex2Char(_Hex)     ("0123456789ABCDEF"[(_Hex)&0x0F])

