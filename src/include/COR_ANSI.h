/************************************************|
 * 描述:    协程-断点初始化
 * 宏名:    _COR_Init
 * 参数[I]: COR_BP_t BP   //协程断点
 * 返回:    无
 * 说明:    无
 ************************************************/
#define _COR_Init(BP)       ((BP) = 0)

/************************************************|
 * 描述:    协程-代码开头
 * 宏名:    _COR_Start
 * 参数[I]: COR_BP_t BP   //协程断点
 * 返回:    无
 * 说明:    协程开头(状态机的开始);
 ************************************************/
#define _COR_Start(BP)      \
    switch((BP)){           \
        case 0:

/************************************************|
 * 描述:    协程-设置断点
 * 宏名:    _COR_SetBP
 * 参数[I]: COR_BP_t BP   //协程断点
 * 返回:    无
 * 说明:    无
 ************************************************/
#define  _COR_SetBP(BP)     \
    (BP) = __LINE__; case __LINE__:

/************************************************|
 * 描述:    协程-跳出
 * 宏名:    _COR_Break
 * 参数[I]: COR_BP_t BP   //协程断点
 * 返回:    无
 * 说明:    直接跳出协程
 ************************************************/
#define  _COR_Break(BP)     \
    goto _XCCOR_GOTO_End;

/************************************************|
 * 描述:    协程-设置断点并跳出
 * 宏名:    _COR_SetBPBreak
 * 参数[I]: COR_BP_t BP   //协程断点
 * 返回:    无
 * 说明:    无
 ************************************************/
#define  _COR_SetBPBreak(BP)    \
    (BP) = __LINE__; goto _XCCOR_GOTO_End; case __LINE__:

/************************************************|
 * 描述:    协程-代码结束
 * 宏名:    _COR_End
 * 参数[I]: COR_BP_t BP   //协程断点
 * 返回:    无
 * 说明:    协程结束(状态机的结尾);
 ************************************************/
#define _COR_End()      \
    }                   \
    _XCCOR_GOTO_End:    /*结束跳转标志*/

