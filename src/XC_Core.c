//=== 任务通知的用户函数

/************************************************|
 * 描述:    发送通知
 * 函数名:  XC_SendNotify
 * 参数[I]: XCOS_t* phXCOS      //通知的XCOS框架
 * 参数[I]: XCTCB_t* phTCB      //通知的任务
 * 参数[I]: XCVar_t NotifyData  //通知传递的数据
 * 返回:    void
 * 说明:
 *  释放一个通知(发送通知,完成通知);
 *  任意位置可调用;
 ************************************************/
void XC_SendNotify(XCOS_t* phXCOS, XCTCB_t* phTCB, XCVar_t NotifyData)
{
    XCSch_ListNodeRemove(phXCOS, phTCB);                //移除节点
    XCSch_ListNodeInsertIndexPrevious(phXCOS, phTCB);   //插入就绪表
    phTCB->NotifyData = NotifyData;
    phTCB->WakeType   = _XC_Wake_Notify;
}

