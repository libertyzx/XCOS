//=== 需要配置的参数

/**
 * @brief   [用户]XCOS基础数据类型
 * @details
 *  默认32位,用于系统滴答计数的数据
 *  一般不用改
 */
#ifndef XC_Tick_t
#define XC_Tick_t uint32_t
#endif

/************************************************ 我是分割线 ************************************************/

/**
 * @brief   [内部]最大任务数
 * @details
 *  因为是协作式调度,任务数太多会导致每个任务运行卡顿;
 *  这个参数限制最大能注册的任务;
 *  数值范围:10~255;
 *  默认:100
 */
#ifndef XC_CFG_MAX_TASKS
#define XC_CFG_MAX_TASKS (100)
#endif

/************************************************ 我是分割线 ************************************************/

/**
 * @brief   [内部]系统每秒滴答数(滴答计数频率)
 * @details
 *  单位Hz,是系统最小的时间单位;
 *  最大值是1000000Hz;对应时间是1us;
 *  一般设置1000,对应时间为1ms;
 */
#ifndef XC_CFG_TICKS_PER_SEC
#define XC_CFG_TICKS_PER_SEC (1000)
#endif

/************************************************ 我是分割线 ************************************************/

/**
 * @brief   [内部]系统滴答计数实现
 * @details
 *  滴答计数是一个累加值,累加时间必须和"XC_CFG_TICKS_PER_SEC"时间一致;
 *  此值会在操作中被读取,作为时间计算的依据;
 *  系统滴答计数可用2种方式使用:
 *--- 方式1:中断累加形式(默认);
 *  用一个变量在定时器中累加,每一个滴答时间则+1;
 *  在此模式下,系统已经定义了一个全局变量"g_SysTickCount"(位于"XC_Sch.c"文件),
 *  并同时在本文件中做了"外部声明全局滴答时间计数";
 *  用户只需要做以下处理即可:
 *      1.创建定时器,按"XC_CFG_TICKS_PER_SEC"计数;
 *      2.在定时器中累加系统滴答计数,即调用"XC_AccSysTickCount()"函数;
 *--- 方式2:计数器形式;
 *  因为协程并不需要中断来切换上下文,所以为了使效率最高可以用一个计数器来做系统滴答计数;
 *  宏"XC_SYS_TICK_COUNT"作为一个计数器的函数的返回值(或其本身寄存器值);
 *  用户需要处理:
 *      1.创建定时器,按"XC_CFG_TICKS_PER_SEC"计数;
 *      2.将计数值作为"XC_SYS_TICK_COUNT"的指向;
 *  注意:
 *      计数器必须是32位计数器;
 *      宏"XC_SYS_TICK_COUNT"会频繁只读调用,注意寄存器读取效率;
 */
#ifndef XC_SYS_TICK_COUNT

#define _XC_SysTickIntIncMode_            // [默认]以中断递增的模式形式
extern volatile XC_Tick_t g_SysTickCount; // 外部声明全局滴答时间计数
#define XC_SYS_TICK_COUNT g_SysTickCount  // 调用滴答时间计数

#endif

