//=== 防重复定义
#ifndef XC_Err_h
#define XC_Err_h
//=== 头文件
#include "XC_Config.h"
#include "XC_Type.h"

/*
 ************************************************************************************************************|
 ************************************************ 我是分割线 ************************************************|
 ************************************************************************************************************|
 */
/** 1) 错误码(开关无关: 类型始终可见, 便于用户实现钩子) */

/**
 * @brief   [用户]错误码
 * @details
 *  上报给 `XC_Err_Hook` 的错误类型; 每次只报"一个错误码", 框架内不保存历史;
 */
typedef enum {
    XC_ERR_NONE           = 0, // 无错误(保留值,框架不会上报此值)
    XC_ERR_FRAME_OVERFLOW = 1, // 帧栈越界: 未配帧栈调用 XC_Cor_Call, 或嵌套层数超过 CorDepthMax
    XC_ERR_ASSERT         = 2, // 断言失败(需同时打开 XC_CFG_ASSERT)
} XC_ErrCode_t;

/*
 ************************************************************************************************************|
 ************************************************ 我是分割线 ************************************************|
 ************************************************************************************************************|
 */
/** 2) 用户钩子与上报宏(开关: XC_CFG_ERR_HOOK) */

#if (XC_CFG_ERR_HOOK != 0)

/**
 * @brief       [用户]错误上报钩子(由用户实现)
 * @param[in]   phTCB       出错的任务控制块(被安全降级/复位前的现场; 断言场景可能为 NULL)
 * @param[in]   ErrCode     错误码(`XC_ErrCode_t`)
 * @details
 *  **开启 `XC_CFG_ERR_HOOK` 后必须由用户提供本函数实现**(否则链接报未定义引用);
 *  调用时机在框架"安全降级处理"**之前** ⇒ `phTCB` 仍是出错现场;
 *  实现要求: 可重入、不阻塞、不调用会移表的框架 API;
 */
extern void XC_Err_Hook(XC_TaskHandle_t phTCB, XC_ErrCode_t ErrCode);

/** [内部]上报一个错误(开关打开时 = 调用用户钩子) */
#define XC_Err_Report(phTCB, ErrCode) XC_Err_Hook((phTCB), (ErrCode))

#else

/** [内部]上报一个错误(开关关闭: 空操作, 实参不求值) */
#define XC_Err_Report(phTCB, ErrCode) ((void)0)

#endif

/*
 ************************************************************************************************************|
 ************************************************ 我是分割线 ************************************************|
 ************************************************************************************************************|
 */
//=== 文件结束
#endif
